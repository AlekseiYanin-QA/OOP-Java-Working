package org.oop;
/**
 * Нарушение:
 Принцип DRY нарушен, так как поля класса объявляются вручную, а затем повторно используются в конструкторе.
 Это может привести к дублированию кода, если в будущем понадобится добавить новые поля или изменить логику инициализации.
 Рекомендация:
 Обратите внимание на возможность использования инструментов, таких как Lombok, чтобы автоматизировать создание
 геттеров, сеттеров и конструкторов. Это поможет избежать дублирования кода.
 */
public class Article {
    public Long id;
    public String title;
    public String content;
    public Long authorId;

    /**
     * Нарушение:
     * Принцип YAGNI нарушен, так как добавлен конструктор по умолчанию, который может не
     * понадобиться в текущей реализации. Это избыточный код, который увеличивает сложность без необходимости.
     *
     * Рекомендация:
     * Убедитесь, что конструктор по умолчанию действительно необходим. Если он не используется, его можно удалить,
     * чтобы упростить код.
     */

    // Конструктор по умолчанию
    public Article() {
    }

    /**
     Нарушение:
     Принцип DRY нарушен, так как инициализация полей в конструкторе дублирует их объявление. Это может привести к
     ошибкам, если поля будут переименованы или изменены.

     Рекомендация:
     Обратите внимание на возможность автоматизации создания конструкторов с параметрами, чтобы избежать дублирования кода.
     */
    // Конструктор с параметрами
    public Article(Long id, String title, String content, Long authorId) {
        this.id = id;
        this.title = title;
        this.content = content;
        this.authorId = authorId;
    }

    /**
     Нарушение:
     Принцип KISS нарушен, так как метод toString() реализован вручную. Это делает его более сложным для поддержки,
     особенно если в будущем добавятся новые поля.

     Рекомендация:
     Рассмотрите возможность автоматической генерации метода toString() с помощью инструментов вроде Lombok.
     Это упростит код и сделает его более поддерживаемым.
     */
    @Override
    public String toString() {
        return "ID: " + id + " | Заголовок: " + title + "\nСодержимое: " + content;
    }
}
